// P6.5: export all editable copy into one reviewable Markdown pack for the
// parish council reviewer ("S"). Generated, do not hand-edit:
//   npm run content:export   ->  ../docs/content-review-pack.md
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { JSON_SCHEMA, load } from "js-yaml";

const dir = [path.resolve("content"), path.resolve("../content")].find((d) =>
  existsSync(path.join(d, "glossary.md")),
);
const fm = (f) =>
  load(
    /^---\r?\n([\s\S]*?)\r?\n---/.exec(
      readFileSync(path.join(dir, f), "utf-8"),
    )[1],
    { schema: JSON_SCHEMA },
  );
const out = [
  "# Content review pack",
  "",
  "**Generated by `npm run content:export` -- do not hand-edit.** This pack reflects the content files at the time it was generated; regenerate it before review. Review the wording below and send feedback to the project lead. Once approved, the files in `content/` get `status: approved`, `reviewed_by` (role only) and `reviewed_on`.",
  "",
  "For each item please say: approve, or what to change.",
  "",
];
for (const f of readdirSync(path.join(dir, "metrics"))
  .filter((f) => f.endsWith(".md"))
  .sort()) {
  const d = fm(`metrics/${f}`);
  out.push(
    `## ${d.metric_id} (status: ${d.status})`,
    "",
    "### What this means",
    "",
    d.what_this_means.trim(),
    "",
    "### Opportunities",
    "",
  );
  for (const o of d.opportunities)
    out.push(
      `- [${o.title}](${o.url}) (${o.provider}): ${o.description} _Last checked ${o.last_checked}._`,
    );
  out.push("", "**Feedback:** ", "");
}
const about = fm("about.md");
out.push(
  `## About page (status: ${about.status})`,
  "",
  ...about.paragraphs.flatMap((p) => [p, ""]),
  "**Feedback:** ",
  "",
);
const meth = fm("methodology.md");
out.push(`## Methodology page (status: ${meth.status})`, "");
for (const sec of meth.sections)
  out.push(`### ${sec.heading}`, "", ...sec.paragraphs.flatMap((p) => [p, ""]));
out.push("**Feedback:** ", "");
const g = fm("glossary.md");
out.push(
  `## Glossary (status: ${g.status})`,
  "",
  ...g.terms.map((t) => `- **${t.term}**: ${t.definition}`),
  "",
  "**Feedback:** ",
  "",
);
writeFileSync(
  path.resolve(process.env.REVIEW_PACK_OUT ?? "../docs/content-review-pack.md"),
  out.join("\n"),
);
console.log("Wrote docs/content-review-pack.md");
